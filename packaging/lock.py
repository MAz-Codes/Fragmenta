#!/usr/bin/env python3
"""Generate the hashed, fully pinned dependency locks the installers sync to.

`requirements.txt` stays the human-edited input (ranges allowed). This
resolves it with uv for each platform and writes `locks/<platform>.txt`, which
`install.py` syncs to exactly (`uv pip sync --require-hashes`). The locks are
committed and live at the top level, so `main` and source installs carry them.

    python packaging/lock.py            # write / refresh the locks
    python packaging/lock.py --check    # CI: fail if a lock is out of date
    python packaging/lock.py --upgrade  # move every pin to the newest allowed

An existing lock's pins are kept unless requirements.txt asks otherwise, so a
re-run only changes what changed. Needs `uv` on PATH.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCKS = ROOT / "locks"
FIND_LINKS = "utils/vendor/wheels"   # sdist-only packages: proxy-tools, antlr4, wget

PLATFORMS = {
    "linux-x86_64-cu128": {
        "triple": "x86_64-unknown-linux-gnu",
        # The packaged Linux app opens in Chromium, not a GTK window.
        "drop": {"pycairo", "pygobject"},
    },
    "windows-x86_64-cu128": {"triple": "x86_64-pc-windows-msvc"},
    # mlx wheels are macosx_14_0+; uv's default macOS target is older.
    "macos-arm64": {"triple": "aarch64-apple-darwin", "env": {"MACOSX_DEPLOYMENT_TARGET": "14.0"}},
}

# In the locks but not in requirements.txt: an exact sync removes anything
# installed outside the lock, and the app installs this one on demand.
EXTRA = ["LinkPython-extern==1.3.0"]
# Installed without its dependencies (its declared ones would drag in an old
# stack); appended to every lock with the wheel's hash.
NO_DEPS = {"laion-clap": "1.1.7"}


def python_version() -> str:
    return (ROOT / ".python-version").read_text(encoding="utf-8").strip()


def requirement_name(line: str) -> str | None:
    m = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", line)
    return m.group(1).lower().replace("_", "-") if m and not line.lstrip().startswith(("#", "-")) else None


def lock_input(drop: set[str]) -> str:
    lines = [l for l in REQUIREMENTS.read_text(encoding="utf-8").splitlines()
             if requirement_name(l) not in drop]
    return "\n".join(lines + EXTRA) + "\n"


def wheel_hash(name: str, version: str) -> tuple[str, str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        files = json.load(r)["urls"]
    whl = next(f for f in files if f["filename"].endswith("-none-any.whl"))
    return whl["filename"], whl["digests"]["sha256"]


def header(platform: str) -> str:
    return (f"# Fragmenta dependency lock: {platform}, Python {python_version()}.\n"
            f"# Generated by packaging/lock.py from requirements.txt. Don't edit by hand:\n"
            f"# change requirements.txt and run `python packaging/lock.py`.\n"
            f"# Sync: uv pip sync --require-hashes --index-strategy unsafe-best-match <this file>\n"
            f"# (the PyTorch index mirrors some PyPI packages at older versions; the\n"
            f"# hashes pin every file, so taking the best match across indexes is safe).\n")


def compile_lock(platform: str, spec: dict, out: Path, upgrade: bool) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        inp = Path(tmp) / "requirements.in"
        inp.write_text(lock_input(spec.get("drop", set())), encoding="utf-8")
        # Seed with the current lock so its pins are preferred.
        work = Path(tmp) / "lock.txt"
        if out.exists():
            shutil.copy(out, work)
        cmd = ["uv", "pip", "compile", str(inp), "--output-file", str(work),
               "--python-version", python_version(), "--python-platform", spec["triple"],
               "--index-strategy", "unsafe-best-match", "--generate-hashes",
               "--find-links", FIND_LINKS, "--emit-index-url", "--emit-find-links",
               "--no-annotate", "--no-header", "--quiet"]
        if upgrade:
            cmd.append("--upgrade")
        env = {**os.environ, **spec.get("env", {})}
        subprocess.run(cmd, cwd=ROOT, env=env, check=True)
        body = work.read_text(encoding="utf-8")
        body = "\n".join(l for l in body.splitlines() if not l.startswith("#")).strip("\n") + "\n"
        # Drop a previous run's no-deps tail before appending a fresh one.
        body = body.split("\n# Installed without dependencies", 1)[0].rstrip("\n") + "\n"
        tail = ["", "# Installed without dependencies (see NO_DEPS in packaging/lock.py)."]
        for name, version in NO_DEPS.items():
            _, sha = wheel_hash(name, version)
            tail.append(f"{name}=={version} \\\n    --hash=sha256:{sha}")
        out.write_text(header(platform) + body + "\n".join(tail) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a committed lock is out of date")
    ap.add_argument("--upgrade", action="store_true", help="move every pin to the newest allowed")
    ap.add_argument("--platform", choices=sorted(PLATFORMS), action="append", help="only these (default: all)")
    args = ap.parse_args()
    if not shutil.which("uv"):
        print("lock.py needs uv on PATH (https://docs.astral.sh/uv/)", file=sys.stderr)
        return 2
    LOCKS.mkdir(exist_ok=True)
    stale = []
    for platform in args.platform or PLATFORMS:
        target = LOCKS / f"{platform}.txt"
        if args.check:
            with tempfile.TemporaryDirectory() as tmp:
                probe = Path(tmp) / target.name
                if target.exists():
                    shutil.copy(target, probe)
                compile_lock(platform, PLATFORMS[platform], probe, upgrade=False)
                old = target.read_text(encoding="utf-8") if target.exists() else ""
                new = probe.read_text(encoding="utf-8")
                if old != new:
                    stale.append(platform)
                    sys.stdout.writelines(difflib.unified_diff(
                        old.splitlines(True), new.splitlines(True), f"locks/{target.name}", "regenerated"))
            continue
        compile_lock(platform, PLATFORMS[platform], target, upgrade=args.upgrade)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:12]
        pins = sum(1 for l in target.read_text(encoding="utf-8").splitlines() if re.match(r"^[A-Za-z0-9]", l))
        print(f"locks/{target.name}: {pins} packages (sha256 {digest})")
    if stale:
        print(f"\nout of date: {', '.join(stale)} — run `python packaging/lock.py` and commit locks/", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
